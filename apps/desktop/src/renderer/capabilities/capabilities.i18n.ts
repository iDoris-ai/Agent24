// CapabilityDef carries string keys, including names supplied by dynamic manifests.
export const capabilitiesMessages: Messages<string> = messages

/** Daemon-supplied names and descriptions are metadata shared across UI locales. */
export function registerDynamicMessages(id: string, name: string, description?: string) {
  const nameKey = `module.${id}.name`
  const descKey = `module.${id}.description`
  for (const table of Object.values(capabilitiesMessages)) {
    table[nameKey] = name
    table[descKey] = description || table['dynamic.description']
  }
  return { nameKey, descKey }
}
