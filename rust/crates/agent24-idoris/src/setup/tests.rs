#[test]
fn upstream_gate_uses_semver() {
    // No environment mutation: the debug override is process-wide.
    let override_on =
        cfg!(debug_assertions) && std::env::var("AGENT24_DEV_IDORIS_V6").as_deref() == Ok("1");
    let mut lock = crate::IdorisLock::embedded().clone();
    for (tag, enabled) in [
        ("v0.5.0", false),
        ("v0.6.0-rc.1", false),
        ("v0.6.0", true),
        ("0.6.1", true),
        ("v0.10.0", true),
        ("invalid", false),
    ] {
        lock.tag = tag.into();
        assert_eq!(upstream_setup_enabled(&lock), enabled || override_on);
    }
    if !override_on {
        assert!(!upstream_setup_enabled(crate::IdorisLock::embedded()));
    }
}

