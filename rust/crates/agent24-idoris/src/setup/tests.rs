#![allow(clippy::unwrap_used)]
use super::*;
use std::{fs, os::unix::fs::PermissionsExt};

struct Fixture {
    dir: tempfile::TempDir,
    installed: InstalledVersion,
    probe: ProbeResult,
}
impl Fixture {
    fn new(body: &str) -> Self {
        let dir = tempfile::tempdir().unwrap();
        let version = dir.path().join("0.4.0");
        fs::create_dir(&version).unwrap();
        let script = format!(
            "#!/bin/sh\nset -eu\n{}\n{}\n",
            include_str!("../../tests/fixtures/setup.sh"),
            body
        );
        fs::write(version.join("idoris"), script).unwrap();
        fs::set_permissions(version.join("idoris"), fs::Permissions::from_mode(0o700)).unwrap();
        Self {
            installed: InstalledVersion::from_test_directory(version, "idoris"),
            dir,
            probe: ProbeResult {
                endpoint: Endpoint::parse("http://127.0.0.1:8088").unwrap(),
                identity: ServiceIdentity::Omlx,
                status: ProbeStatus::Ready {
                    models: vec!["real-model".into()],
                },
            },
        }
    }
    fn root(&self) -> PathBuf {
        self.dir.path().join("instances/test")
    }
    async fn run(&self, timeout: Duration) -> Result<SetupOutcome, SetupError> {
        run_setup_with_timeout(
            &self.installed,
            &self.root(),
            &self.probe,
            Some(Zeroizing::new("stdin-secret".into())),
            &[(Role::Daily, "real-model".into())],
            Some(SetupBudget(0)),
            &CancellationToken::new(),
            timeout,
        )
        .await
    }
}
const OK: &str = r#"
/bin/mkdir -p "$out"
printf 'generated by idoris' > "$out/omlx.yaml"
printf 'generated by idoris' > "$out/subscription.yaml"
printf '{"status":"ok","endpoint":"http://127.0.0.1:8088","auth":"required","models":["real-model"],"bindings":{"daily":"real-model"},"components_dir":"%s","next":{"env":{"IDORIS_COMPONENTS_DIR":"%s"},"needs_env":["IDORIS_OMLX_API_KEY"]}}\n' "$out" "$out"
"#;

#[tokio::test]
async fn success_uses_stdin_only_and_preserves_zero_budget() {
    let f = Fixture::new(OK);
    let result = f.run(Duration::from_secs(3)).await.unwrap();
    assert_eq!(
        result.bindings,
        BTreeMap::from([(Role::Daily, "real-model".into())])
    );
    assert!(
        result
            .components_dir
            .starts_with(f.root().canonicalize().unwrap().join("components"))
    );
    assert_eq!(
        fs::read_to_string(result.components_dir.join("omlx.yaml")).unwrap(),
        "generated by idoris"
    );
}

#[tokio::test]
async fn all_frozen_error_codes_are_typed_and_retained() {
    for code in [
        "unreachable",
        "auth_required",
        "auth_failed",
        "not_omlx",
        "model_not_found",
        "invalid_endpoint",
        "invalid_role",
        "out_dir_not_empty",
        "validation_failed",
        "write_failed",
        "invalid_api_key_input",
    ] {
        let f = Fixture::new(&format!(
            "printf '%s\\n' '{{\"status\":\"error\",\"code\":\"{code}\",\"message\":\"stdin-secret\"}}'\nexit 1"
        ));
        let err = f.run(Duration::from_secs(3)).await.unwrap_err();
        assert!(
            matches!(&err, SetupError::Rejected(c) if c.code() == code),
            "{err:?}"
        );
        assert!(!format!("{err:?} {err}").contains("stdin-secret"));
    }
}

#[tokio::test]
