#[test]
fn budget_requires_sources_and_reuses_hardware_allocation() {
    let profile: agent24_hw::HardwareProfile = serde_json::from_value(serde_json::json!({
        "total_mem_bytes": 8589934592_u64, "avail_mem_bytes": 1,
        "arch": "aarch64", "cpu_cores": 8, "accelerator": "metal", "os": "macos"
    }))
    .unwrap();
    let report = agent24_hw::HardwareReport::new(profile, None);
    assert!(SetupBudget::from_report(None, Some(0)).is_err());
    assert!(SetupBudget::from_report(Some(&report), None).is_err());
    let mut unknown = report.clone();
    unknown.profile.total_mem_bytes = 0;
    assert!(SetupBudget::from_report(Some(&unknown), Some(0)).is_err());
    for core in [0, 1234, report.usable_bytes, u64::MAX] {
        assert_eq!(
            SetupBudget::from_report(Some(&report), Some(core))
                .unwrap()
                .bytes(),
            report.idoris_budget_bytes(core)
        );
    }
}

