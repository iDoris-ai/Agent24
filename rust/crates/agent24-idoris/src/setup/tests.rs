#[tokio::test]
async fn upstream_errors_and_process_limits() {
    for code in [
        "invalid_endpoint",
        "unreachable",
        "not_openai_compatible",
        "auth_required",
        "model_not_found",
        "invalid_role",
        "invalid_id",
        "id_conflict",
        "out_dir_not_empty",
        "validation_failed",
        "write_failed",
        "future_code",
    ] {
        let f = UpstreamFixture::new(&format!(
            "printf '%s\\n' '{{\"status\":\"error\",\"code\":\"{code}\",\"message\":\"secret\"}}'; exit 1"
        ));
        let error = f.run(false, Duration::from_secs(5)).await.unwrap_err();
        let expected = if code == "future_code" {
            "setup_failed"
        } else {
            code
        };
        assert!(
            matches!(error, SetupError::Rejected(c) if c.code() == expected),
            "{error:?}"
        );
    }
    for (body, expected) in [
        ("echo usage >&2; exit 1", "invalid"),
        ("exec /bin/sleep 10", "timeout"),
        ("/usr/bin/head -c 1048577 /dev/zero", "oversized"),
        ("/usr/bin/head -c 1048577 /dev/zero >&2", "oversized"),
    ] {
        let f = UpstreamFixture::new(body);
        let timeout = if expected == "timeout" {
            Duration::from_millis(100)
        } else {
            Duration::from_secs(5)
        };
        let error = f.run(false, timeout).await.unwrap_err();
        assert!(matches!(
            (expected, error),
            ("invalid", SetupError::InvalidResponse)
                | ("timeout", SetupError::TimedOut)
                | ("oversized", SetupError::OutputTooLarge)
        ));
    }
}

